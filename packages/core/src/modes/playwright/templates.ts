import type { Tier } from '../../storage/types.js';

/** The three tiers a scaffolded suite always provisions, in execution order. */
export const TIERS: Tier[] = ['tierA-public', 'tierB-auth', 'tierC-api'];

/** Map a tier id to a short, human-readable label (used in READMEs / comments). */
export function tierLabel(tier: Tier): string {
  switch (tier) {
    case 'tierA-public':
      return 'Tier A — Public (no auth)';
    case 'tierB-auth':
      return 'Tier B — Authenticated (per-role)';
    case 'tierC-api':
      return 'Tier C — API / backend';
    default:
      return String(tier);
  }
}

/** Pinned versions so the exported suite is reproducible without the monorepo. */
const PLAYWRIGHT_TEST_VERSION = '^1.49.0';

export interface PackageJsonOptions {
  name?: string;
}

/** package.json for a standalone, runnable Playwright project. */
export function packageJsonContents(opts: PackageJsonOptions = {}): string {
  const pkg = {
    name: opts.name ?? 'healix-suite',
    version: '0.0.0',
    private: true,
    description: 'Playwright test suite generated by Healix.',
    type: 'module',
    scripts: {
      test: 'playwright test',
      'test:tierA': 'playwright test --project=tierA-public',
      'test:tierB': 'playwright test --project=tierB-auth',
      'test:tierC': 'playwright test --project=tierC-api',
      report: 'playwright show-report',
    },
    devDependencies: {
      '@playwright/test': PLAYWRIGHT_TEST_VERSION,
    },
  };
  return `${JSON.stringify(pkg, null, 2)}\n`;
}

export interface ConfigOptions {
  baseUrl?: string | null;
}

/**
 * playwright.config.ts wiring the three Healix tiers as Playwright projects,
 * a JSON + HTML reporter, and the artifact policy: every test records a
 * screenshot + video (so the run detail can always show what happened), while
 * traces are kept only for failures. Tier B depends on an auth storageState
 * produced by fixtures/auth.setup.ts; when no credentials are wired the setup
 * is a no-op and Tier B specs simply run unauthenticated.
 */
export function playwrightConfigContents(opts: ConfigOptions = {}): string {
  const baseUrl = (opts.baseUrl ?? '').trim();
  // Always honor the HEALIX_BASE_URL env override, even when a literal default is baked in.
  const baseUrlLiteral = baseUrl
    ? `process.env.HEALIX_BASE_URL || ${JSON.stringify(baseUrl)}`
    : "process.env.HEALIX_BASE_URL || 'http://localhost:3000'";

  return `import { defineConfig, devices } from '@playwright/test';

/**
 * Healix-generated Playwright config.
 * Projects mirror the Healix tiers; edit baseURL via HEALIX_BASE_URL or below.
 */
export default defineConfig({
  testDir: './tests',
  fullyParallel: true,
  forbidOnly: !!process.env.CI,
  // Retries drive Healix's flaky detection (a test must fail then pass on retry
  // to register as flaky). Default to 1 locally too — gating on CI meant flaky
  // was never detectable on a local \`healix run\`. Override with HEALIX_RETRIES.
  retries: process.env.HEALIX_RETRIES ? Number(process.env.HEALIX_RETRIES) : process.env.CI ? 2 : 1,
  // One worker by default: the suite drives a SINGLE live app instance whose
  // state is shared across tests — parallel workers make tests interfere
  // (add-task racing a count assertion). Override with HEALIX_WORKERS.
  workers: process.env.HEALIX_WORKERS ? Number(process.env.HEALIX_WORKERS) : 1,
  timeout: 60_000,
  expect: { timeout: 10_000 },
  reporter: [
    ['json', { outputFile: 'results.json' }],
    ['html', { open: 'never' }],
    ['list'],
  ],
  use: {
    baseURL: ${baseUrlLiteral},
    screenshot: 'on',
    video: 'on',
    trace: 'retain-on-failure',
  },
  projects: [
    {
      name: 'auth-setup',
      // Override the inherited testDir ('./tests') so the setup file under
      // ./fixtures is actually discovered by testMatch.
      testDir: '.',
      testMatch: /fixtures\\/auth\\.setup\\.ts/,
    },
    {
      name: 'tierA-public',
      testDir: './tests/tierA-public',
      use: { ...devices['Desktop Chrome'] },
    },
    {
      name: 'tierB-auth',
      testDir: './tests/tierB-auth',
      use: {
        ...devices['Desktop Chrome'],
        storageState: 'fixtures/.auth/user.json',
      },
      dependencies: ['auth-setup'],
    },
    {
      name: 'tierC-api',
      testDir: './tests/tierC-api',
      use: { ...devices['Desktop Chrome'] },
    },
  ],
});
`;
}

/**
 * Auth setup fixture. Healix injects real credentials into fixtures/.auth at
 * runtime; absent those, this writes an empty storageState so Tier B can still
 * load (specs then run as an anonymous user). A genuine login failure should
 * throw here — Healix surfaces that as a `blocked` Tier B outcome.
 */
export function authSetupContents(): string {
  return `import { test as setup } from '@playwright/test';
import { mkdir, writeFile, access } from 'node:fs/promises';
import { dirname } from 'node:path';

const authFile = 'fixtures/.auth/user.json';
// Sidecar read by Healix after the run: records whether a REAL login was
// performed, so Tier B failures can be classified structurally (blocked vs
// genuine) instead of by matching error text.
const metaFile = 'fixtures/.auth/setup-meta.json';

async function writeMeta(performedLogin) {
  await writeFile(
    metaFile,
    JSON.stringify({ performedLogin, at: new Date().toISOString() }),
    'utf-8',
  );
}

/**
 * Establishes the Tier B authenticated storageState. By default this produces an
 * empty (anonymous) state. Wire your real login flow here, or have Healix inject
 * credentials via HEALIX_TIERB_* env vars. Throwing here marks Tier B blocked.
 */
setup('authenticate', async ({ page }) => {
  await mkdir(dirname(authFile), { recursive: true });

  const email = process.env.HEALIX_TIERB_EMAIL;
  const password = process.env.HEALIX_TIERB_PASSWORD;
  const loginUrl = process.env.HEALIX_TIERB_LOGIN_URL;

  if (email && password && loginUrl) {
    // Written BEFORE the login attempt so a mid-login crash still leaves
    // performedLogin:false on disk; overwritten with true only on success.
    await writeMeta(false);
    await page.goto(loginUrl);
    await page.getByLabel(/email/i).fill(email);
    await page.getByLabel(/password/i).fill(password);
    await page.getByRole('button', { name: /sign in|log ?in|continue/i }).click();
    await page.waitForLoadState('networkidle').catch(() => {});
    await page.context().storageState({ path: authFile });
    await writeMeta(true);
    return;
  }

  await writeMeta(false);
  try {
    await access(authFile);
  } catch {
    await writeFile(authFile, JSON.stringify({ cookies: [], origins: [] }), 'utf-8');
  }
});
`;
}

