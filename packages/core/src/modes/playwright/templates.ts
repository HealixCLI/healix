/**
 * Auth setup rebuilt by the HEAL phase: model-proposed login STEPS are injected
 * into this TRUSTED wrapper. The wrapper owns everything security-relevant
 * (imports, credential env reads, storageState + sidecar-meta writes); the
 * steps may only drive `page` and read the two credential constants. Steps are
 * validated by the caller (no imports/require/eval/fs/child_process) before
 * they get here.
 */
export function authSetupWithStepsContents(steps: string): string {
  const indented = steps
    .split('\n')
    .map((line) => (line.trim().length > 0 ? `  ${line}` : line))
    .join('\n');
  return `import { test as setup } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';

const authFile = 'fixtures/.auth/user.json';
const metaFile = 'fixtures/.auth/setup-meta.json';

async function writeMeta(performedLogin) {
  await writeFile(
    metaFile,
    JSON.stringify({ performedLogin, at: new Date().toISOString(), healed: true }),
    'utf-8',
  );
}

// Regenerated by Healix self-heal from the live login page.
setup('authenticate', async ({ page }) => {
  await mkdir(dirname(authFile), { recursive: true });
  await writeMeta(false);

  const email = process.env.HEALIX_TIERB_EMAIL ?? '';
  const password = process.env.HEALIX_TIERB_PASSWORD ?? '';
  const loginUrl = process.env.HEALIX_TIERB_LOGIN_URL ?? '/login';

${indented}

  await page.context().storageState({ path: authFile });
  await writeMeta(true);
});
`;
}
